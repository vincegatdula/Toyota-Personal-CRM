import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { analyzeWorkbook } from "../lib/import/analyze";
import type { ImportPreview } from "../lib/import/types";

const workbookPath = process.argv[2] ?? "Personal Toyota CRM.xlsx";
const outputPath = process.argv[3] ?? "supabase/import-workbook-data.sql";

const buffer = readFileSync(path.resolve(workbookPath));
const preview = analyzeWorkbook(buffer, path.basename(workbookPath));

function text(value: string | null | undefined): string {
  if (value === null || value === undefined || value === "") return "NULL";
  return `'${value.replace(/'/g, "''")}'`;
}

function date(value: string | null | undefined): string {
  return text(value);
}

function number(value: number | null | undefined): string {
  return value === null || value === undefined ? "NULL" : String(value);
}

function boolean(value: boolean): string {
  return value ? "true" : "false";
}

function leadSelect(leadKey: string): string {
  return `(select l.id from public.leads l where l.owner_id = v_owner and l.legacy_key = ${text(leadKey)})`;
}

function buildSql(preview: ImportPreview): string {
  const lines: string[] = [];
  lines.push("-- ============================================================================");
  lines.push("-- Personal Toyota CRM - workbook data snapshot");
  lines.push("-- Auto-generated by `npm run seed:generate`. Do not edit by hand.");
  lines.push("--");
  lines.push("-- The in-app import wizard is the primary migration path. Use this file only");
  lines.push("-- as a convenience: it attaches the workbook records to the FIRST profile in");
  lines.push("-- public.profiles.");
  lines.push("--");
  lines.push("-- Before running:");
  lines.push("--   1. Apply supabase/migrations/0001_schema.sql, 0002_rls.sql, 0003_seed_lists.sql, 0004_security_hardening.sql");
  lines.push("--   2. Create your account in the app so a profile exists");
  lines.push("--   3. Run this file in the Supabase SQL editor");
  lines.push("--");
  lines.push(`-- Source workbook: ${preview.filename}`);
  lines.push(`-- Generated: ${preview.generatedAt}`);
  lines.push(
    `-- Records: ${preview.leads.length} prospects, ${preview.financing.length} financing, ` +
      `${preview.reservations.length} reservations, ${preview.releases.length} releases, ` +
      `${preview.lostSales.length} lost sales`,
  );
  lines.push(
    `-- Preview issues: ${preview.summary.errors} errors, ${preview.summary.warnings} warnings, ${preview.summary.info} info`,
  );
  lines.push("-- ============================================================================");
  lines.push("");
  lines.push("begin;");
  lines.push("");
  lines.push("do $$");
  lines.push("declare");
  lines.push("  v_owner uuid;");
  lines.push("begin");
  lines.push("  select id into v_owner from public.profiles order by created_at limit 1;");
  lines.push("  if v_owner is null then");
  lines.push("    raise exception 'Create an account in the app before seeding workbook data.';");
  lines.push("  end if;");
  lines.push("");

  lines.push("  -- Prospects ---------------------------------------------------------------");
  for (const lead of preview.leads) {
    lines.push(
      "  insert into public.leads (" +
        [
          "owner_id",
          "legacy_key",
          "date_created",
          "lead_source",
          "prospect_name",
          "preferred_model",
          "transaction",
          "sales_channel",
          "purchase_timeline",
          "pipeline_status",
          "last_contact_date",
          "next_action",
          "next_action_due_date",
          "contact_number",
          "email",
          "location",
          "remarks",
          "lost_at",
        ].join(", ") +
        ")",
    );
    lines.push("  values (");
    lines.push("    v_owner,");
    lines.push(`    ${text(lead.legacyKey)},`);
    lines.push(`    ${date(lead.dateCreated)},`);
    lines.push(`    ${text(lead.leadSource)},`);
    lines.push(`    ${text(lead.prospectName)},`);
    lines.push(`    ${text(lead.preferredModel)},`);
    lines.push(`    ${text(lead.transaction)},`);
    lines.push(`    ${text(lead.salesChannel)},`);
    lines.push(`    ${date(lead.purchaseTimeline)},`);
    lines.push(`    ${text(lead.pipelineStatus)},`);
    lines.push(`    ${date(lead.lastContactDate)},`);
    lines.push(`    ${text(lead.nextAction)},`);
    lines.push(`    ${date(lead.nextActionDueDate)},`);
    lines.push(`    ${text(lead.contactNumber)},`);
    lines.push(`    ${text(lead.email)},`);
    lines.push(`    ${text(lead.location)},`);
    lines.push(`    ${text(lead.remarks)},`);
    lines.push(
      `    ${date(
        lead.pipelineStatus === "Lost" && lead.dateCreated
          ? `${lead.dateCreated}T12:00:00+08:00`
          : null,
      )}`,
    );
    lines.push("  )");
    lines.push(
      "  on conflict (owner_id, legacy_key) where legacy_key is not null do nothing;",
    );
  }
  lines.push("");

  if (preview.financing.length) {
    lines.push("  -- Financing applications --------------------------------------------------");
    for (const row of preview.financing) {
      lines.push(
        "  insert into public.financing_applications (owner_id, legacy_key, lead_id, date_submitted, lead_source, preferred_model, bank, application_status, date_approval, approved_dp, date_released, remarks)",
      );
      lines.push(
        `  select v_owner, ${text(row.legacyKey)}, ${leadSelect(row.leadKey)}, ${date(row.dateSubmitted)}, ${text(row.leadSource)}, ${text(row.preferredModel)}, ${text(row.bank)}, ${text(row.applicationStatus)}, ${date(row.dateApproval)}, ${number(row.approvedDp)}, ${date(row.dateReleased)}, ${text(row.remarks)}`,
      );
      lines.push(
        "  on conflict (owner_id, legacy_key) where legacy_key is not null do nothing;",
      );
    }
    lines.push("");
  }

  if (preview.reservations.length) {
    lines.push("  -- Reservations ------------------------------------------------------------");
    for (const row of preview.reservations) {
      lines.push(
        "  insert into public.reservations (owner_id, legacy_key, lead_id, reservation_date, reserved_model, sales_channel, current_status, expected_release_date, last_customer_update, next_action, remarks)",
      );
      lines.push(
        `  select v_owner, ${text(row.legacyKey)}, ${leadSelect(row.leadKey)}, ${date(row.reservationDate)}, ${text(row.reservedModel)}, ${text(row.salesChannel)}, ${text(row.currentStatus)}, ${date(row.expectedReleaseDate)}, ${text(row.lastCustomerUpdate)}, ${text(row.nextAction)}, ${text(row.remarks)}`,
      );
      lines.push(
        "  on conflict (owner_id, legacy_key) where legacy_key is not null do nothing;",
      );
    }
    lines.push("");
  }

  if (preview.releases.length) {
    lines.push("  -- Vehicle releases --------------------------------------------------------");
    for (const row of preview.releases) {
      lines.push(
        "  insert into public.vehicle_releases (owner_id, legacy_key, lead_id, release_date, transaction, model_released, units_released, bank, remarks)",
      );
      lines.push(
        `  select v_owner, ${text(row.legacyKey)}, ${leadSelect(row.leadKey)}, ${date(row.releaseDate)}, ${text(row.transaction)}, ${text(row.modelReleased)}, ${number(row.unitsReleased)}, ${text(row.bank)}, ${text(row.remarks)}`,
      );
      lines.push(
        "  on conflict (owner_id, legacy_key) where legacy_key is not null do nothing;",
      );
    }
    lines.push("");
  }

  if (preview.lostSales.length) {
    lines.push("  -- Lost sales --------------------------------------------------------------");
    for (const row of preview.lostSales) {
      lines.push(
        "  insert into public.lost_sales (owner_id, legacy_key, lead_id, date_marked_lost, lead_source, preferred_model, pipeline_stage_when_lost, primary_loss_reason, competitor_alternative, financing_payment_issue, estimated_units_lost, recoverable, recovery_next_action, coaching_notes)",
      );
      lines.push(
        `  select v_owner, ${text(row.legacyKey)}, ${leadSelect(row.leadKey)}, ${date(row.dateMarkedLost)}, ${text(row.leadSource)}, ${text(row.preferredModel)}, ${text(row.pipelineStageWhenLost)}, ${text(row.primaryLossReason)}, ${text(row.competitorAlternative)}, ${text(row.financingPaymentIssue)}, ${number(row.estimatedUnitsLost)}, ${boolean(row.recoverable)}, ${text(row.recoveryNextAction)}, ${text(row.coachingNotes)}`,
      );
      lines.push(
        "  on conflict (owner_id, legacy_key) where legacy_key is not null do nothing;",
      );
    }
    lines.push("");
  }

  lines.push("  raise notice 'Workbook snapshot applied for owner %', v_owner;");
  lines.push("end $$;");
  lines.push("");
  lines.push("commit;");
  lines.push("");

  if (preview.issues.length) {
    lines.push("-- ============================================================================");
    lines.push("-- Import review notes (also visible in the in-app import preview)");
    lines.push("-- ============================================================================");
    for (const issue of preview.issues) {
      lines.push(
        `-- [${issue.severity}] ${issue.sheet}${issue.row ? ` row ${issue.row}` : ""}: ${issue.message}`,
      );
      lines.push(`--   Action: ${issue.action}`);
    }
    lines.push("");
  }

  return lines.join("\n");
}

writeFileSync(outputPath, buildSql(preview), "utf8");
console.log(
  `Wrote ${outputPath}: ${preview.leads.length} prospects, ${preview.financing.length} financing, ` +
    `${preview.reservations.length} reservations, ${preview.releases.length} releases, ` +
    `${preview.lostSales.length} lost sales (${preview.summary.errors} errors, ${preview.summary.warnings} warnings).`,
);
